#!/usr/bin/env node
// Writes apps/<app>/src/environments/environment.ts from build-time variables, so
// production bundles point at the environment's Forge API instead of the committed
// placeholders. Used by the root Dockerfile (Railway) and by vercel.json.
//   usage: node scripts/forge-env.mjs <app>        (e.g. learner)
//
// FORGE_API_BASE_URL set    -> write the file (any platform).
// unset, on Vercel          -> fail the build: without it nobody can sign in.
// unset, anywhere else      -> keep the committed file (local, CI, docker compose).
// The storefront makes no API calls, so it only needs FORGE_ROOT_DOMAIN.
//
// Everything written here ends up in a public bundle. Never pass a secret.
import { writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

const DEFAULT_ROOT = 'soteriaforge.com';
const DEFAULT_CONTACT = 'hello@soteriaforge.com';

const clean = (value) => (value?.trim() ? value.trim() : undefined);

/**
 * The environment file for `app`, or `null` to keep the committed one.
 * Throws when the build must fail.
 */
export function environmentFile(app, env) {
  const file = `apps/${app}/src/environments/environment.ts`;
  const rootDomain = clean(env.FORGE_ROOT_DOMAIN) ?? DEFAULT_ROOT;

  if (app === 'storefront') {
    if (!clean(env.FORGE_ROOT_DOMAIN)) return null;
    const environment = {
      production: true,
      rootDomain,
      contactEmail: clean(env.FORGE_CONTACT_EMAIL) ?? DEFAULT_CONTACT,
    };
    return {
      file,
      contents:
        `// Generated by scripts/forge-env.mjs at build time. Not committed.\n` +
        `import type { StorefrontEnvironment } from './storefront-environment';\n\n` +
        `export const environment: StorefrontEnvironment = ${JSON.stringify(environment, null, 2)};\n`,
    };
  }

  const apiBaseUrl = clean(env.FORGE_API_BASE_URL);
  if (!apiBaseUrl) {
    if (env.VERCEL) {
      throw new Error(
        'Missing FORGE_API_BASE_URL. Add it in Project Settings > Environment Variables, then redeploy.',
      );
    }
    return null;
  }
  if (!/^https?:\/\//.test(apiBaseUrl)) {
    throw new Error(`FORGE_API_BASE_URL must start with https:// (got "${apiBaseUrl}")`);
  }
  const environment = {
    production: true,
    apiBaseUrl: apiBaseUrl.replace(/\/+$/, ''),
    rootDomain,
  };
  return {
    file,
    contents:
      `// Generated by scripts/forge-env.mjs at build time. Not committed.\n` +
      `import type { AssuranceEnvironment } from '@assurance/auth';\n\n` +
      `export const environment: AssuranceEnvironment = ${JSON.stringify(environment, null, 2)};\n`,
  };
}

function main() {
  const app = process.argv[2];
  if (!app) {
    console.error('usage: node scripts/forge-env.mjs <app>');
    process.exit(2);
  }
  let result;
  try {
    result = environmentFile(app, process.env);
  } catch (error) {
    console.error(`[forge-env] ${error.message}`);
    process.exit(1);
  }
  if (!result) {
    console.log(`[forge-env] no build variables; keeping apps/${app} environment.ts as committed`);
    return;
  }
  writeFileSync(result.file, result.contents);
  console.log(`[forge-env] wrote ${result.file}`);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) main();
