#!/usr/bin/env node
// Writes apps/<app>/src/environments/environment.ts from Vercel project variables, so
// production bundles carry the real Firebase web config and API URL instead of the
// empty placeholders committed to the repo.
//   usage: node scripts/vercel-env.mjs <app>        (e.g. learner)
// Does nothing outside Vercel, so local and CI builds keep the committed file. On Vercel
// it fails the build when a required variable is missing: an empty Firebase config
// otherwise boots to a blank page (auth/invalid-api-key).
import { writeFileSync } from 'node:fs';

const app = process.argv[2];
if (!app) {
  console.error('usage: node scripts/vercel-env.mjs <app>');
  process.exit(2);
}
if (!process.env.VERCEL) {
  console.log(`[vercel-env] not on Vercel; keeping apps/${app} environment.ts as committed`);
  process.exit(0);
}

const env = process.env;
const required = [
  'FORGE_API_BASE_URL',
  'FIREBASE_API_KEY',
  'FIREBASE_AUTH_DOMAIN',
  'FIREBASE_PROJECT_ID',
  'FIREBASE_STORAGE_BUCKET',
  'FIREBASE_MESSAGING_SENDER_ID',
  'FIREBASE_APP_ID',
];
const missing = required.filter((name) => !env[name]?.trim());
if (missing.length > 0) {
  console.error(`[vercel-env] Missing Vercel environment variables: ${missing.join(', ')}`);
  console.error('Add them in Project Settings > Environment Variables, then redeploy.');
  process.exit(1);
}

const optional = (value) => (value?.trim() ? value.trim() : undefined);
const environment = {
  production: true,
  apiBaseUrl: env.FORGE_API_BASE_URL.trim().replace(/\/+$/, ''),
  rootDomain: optional(env.FORGE_ROOT_DOMAIN) ?? 'soteriaforge.com',
  firebase: {
    apiKey: env.FIREBASE_API_KEY.trim(),
    authDomain: env.FIREBASE_AUTH_DOMAIN.trim(),
    projectId: env.FIREBASE_PROJECT_ID.trim(),
    storageBucket: env.FIREBASE_STORAGE_BUCKET.trim(),
    messagingSenderId: env.FIREBASE_MESSAGING_SENDER_ID.trim(),
    appId: env.FIREBASE_APP_ID.trim(),
    measurementId: optional(env.FIREBASE_MEASUREMENT_ID),
  },
  appCheckSiteKey: optional(env.APP_CHECK_SITE_KEY),
  fcmVapidKey: optional(env.FCM_VAPID_KEY),
};

const file = `apps/${app}/src/environments/environment.ts`;
writeFileSync(
  file,
  `// Generated by scripts/vercel-env.mjs at build time. Not committed.\n` +
    `import type { AssuranceEnvironment } from '@assurance/auth';\n\n` +
    `export const environment: AssuranceEnvironment = ${JSON.stringify(environment, null, 2)};\n`,
);
console.log(`[vercel-env] wrote ${file} (firebase project ${environment.firebase.projectId})`);
